#!/usr/bin/env python3
"""Render RESULTS.md from every reports/*/report.json.

The table is generated, never hand-edited: one row per (dataset, backend,
scenario) taking the most recent run for that cell, with the outcome, hard
gates, wall time, client CPU ratio, server CPU (containerized backends),
host load, and the read/load path. Failures are never hidden by later passes:
a cell that failed in one run and passed in a later run under a different
profile shows both rows when the profile differs (`FALKOR_RESULTSET_SIZE`
etc. are recorded in `profile`).
"""
from __future__ import annotations

import argparse
import glob
import html
import json
import os
import sys
from collections import OrderedDict

parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
parser.add_argument("--since", default="", help="use only run bundles whose stamp is >= this value")
parser.add_argument("--html-rows", metavar="PUBLICATION", default="",
                    help="print the site's per-dataset <table> rows for this dated publication instead of writing RESULTS.md")
args = parser.parse_args()

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
reports = sorted(p for p in glob.glob(os.path.join(root, "reports", "*", "report.json"))
                 if os.path.basename(os.path.dirname(p)) >= args.since)
if not reports:
    sys.exit("no reports/*/report.json found")

order = ["memory", "turso-wal", "turso-mvcc", "ladybug", "lancedb", "postgres", "surreal-http", "surreal-sdk",
         "falkor", "helix-http", "helix-sdk", "neo4j", "neo4j-http", "memgraph", "age"]
# Runs before the HTTP/SDK split recorded the SDK store as plain "surreal".
alias = {"surreal": "surreal-sdk"}

rows: "OrderedDict[tuple, dict]" = OrderedDict()
history: dict = {}  # key -> list of (run, outcome, gates, notes) for superseded cells
gates_total = 0
for path in reports:
    run = os.path.basename(os.path.dirname(path))
    data = json.load(open(path))
    smoke = data.get("summary", {}).get("smoke", False)
    host = data.get("host", {})
    host = f"{host.get('arch', '?')}/{host.get('cpus', '?')}" if host else ""
    # Edge slice per dataset: the smoke default is 200k, Surreal and Helix are
    # capped at 10k by the ladder, a full run has no cap.
    slices = {}
    for d in data.get("datasets", []):
        cap = (d.get("load") or {}).get("truncated_at")
        slices[d["manifest"]["name"]] = f"{cap // 1000}k" if cap else "full"
    for r in data["results"]:
        o = r.get("observations", {})
        slice_ = slices.get(r["dataset"], "200k" if smoke else "full")
        key = (r["dataset"], alias.get(r["backend"], r["backend"]), r["scenario"], slice_, o.get("profile") or "")
        if key in rows:
            prev = rows[key]
            history.setdefault(key, []).append((prev["run"], prev["outcome"], prev["gates"], prev["notes"]))
        lat = r.get("latency") or {}
        rows[key] = {
            "run": run,
            "outcome": r["outcome"],
            "gates": sum(v for v in r["gates"].values()),
            "wall_ms": r.get("wall_ms"),
            "cpu": o.get("client_cpu_ratio"),
            "server_cpu_ms": (o.get("server_cpu_us") or 0) // 1000 if o.get("server_cpu_us") is not None else None,
            "load1m": o.get("host_loadavg_1m_end"),
            "p50_us": lat.get("p50_us"),
            "p99_us": lat.get("p99_us"),
            "path": " ".join(filter(None, [o.get("read_path") or o.get("load_path"), o.get("profile") and f"({o['profile']})"])),
            "transport": o.get("transport"),
            "edges_per_s": o.get("edges_per_s"),
            "notes": "; ".join(r.get("notes", []))[:120],
            "slice": slice_,
            # Host CPU steal during the scenario (all vCPUs summed): a burstable
            # instance out of credits shows it while the load average stays flat.
            "host": host + (f", steal {o['host_steal_us'] / 1e6:.1f}s" if o.get("host_steal_us") else ""),
        }

def sort_key(k):
    d, b, s, slice_, profile = k
    return (d, order.index(b) if b in order else 99, s, slice_, profile)

out = ["# GRAPH-ADVERSARIAL-v1 — results", "",
       "Generated by `scripts/render-results.py` from `reports/*/report.json`; do not edit.",
       "Latest run per (dataset, backend, scenario, edge slice, profile). Wall times are upper bounds on a",
       "shared host — compare CPU columns and the recorded load average. `Host` is arch/vCPUs:",
       "`aarch64/*` rows are the contended laptop, `x86_64/4` the dedicated EC2 host. `Slice` is",
       "the edge cap the dataset was truncated to (smoke default 200k; Surreal and Helix 10k).", ""]
current = None
site_rows: "OrderedDict[str, list]" = OrderedDict()
for key in sorted(rows, key=sort_key):
    d, b, s, slice_, _profile = key
    v = rows[key]
    if d != current:
        current = d
        site_rows[d] = []
        out += ["", f"## {d}", "",
                "| Backend | Scenario | Slice | Outcome | Gates | Wall ms | Client CPU | Server CPU ms | p50 µs | p99 µs | Load 1m | Host | Path | Notes |",
                "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    fmt = lambda x, f="{}": ("" if x is None else f.format(x))
    earlier = [h for h in history.get(key, []) if h[2] > 0 or h[1] != v["outcome"]]
    if earlier:
        v = dict(v)
        v["notes"] = (v["notes"] + " " if v["notes"] else "") + "; ".join(
            f"earlier {h[1]} (gates={h[2]}) in {h[0]}: {h[3]}" for h in earlier
        )
    out.append(
        f"| {b} | {s} | {slice_} | {v['outcome']} | {v['gates']} | {fmt(v['wall_ms'])} | "
        f"{fmt(v['cpu'], '{:.2f}')} | {fmt(v['server_cpu_ms'])} | {fmt(v['p50_us'])} | {fmt(v['p99_us'])} | "
        f"{fmt(v['load1m'], '{:.0f}')} | {v['host']} | {v['path']} | {v['notes']} |"
    )
    run_link = f'<a href="/evidence/strain/{args.html_rows}/{v["run"]}/report.json">{v["run"]}</a>'
    site_rows[d].append("<tr>" + "".join(f"<td>{c}</td>" for c in [
        b, s, slice_, v["outcome"], v["gates"], fmt(v["wall_ms"]), fmt(v["cpu"], "{:.2f}"), fmt(v["server_cpu_ms"]),
        fmt(v["p50_us"]), fmt(v["p99_us"]), fmt(v["load1m"], "{:.0f}"), run_link, html.escape(v["notes"]),
    ]) + "</tr>")
    gates_total += v["gates"]
superseded_fail = sum(1 for hs in history.values() for h in hs if h[2] > 0)
out += ["", f"Latest-cell hard-gate total: **{gates_total}** across {len(rows)} cells from {len(reports)} runs; "
        f"{superseded_fail} earlier failing cell(s) are kept in the Notes column of their superseding row."]
if args.html_rows:
    # The site's results tables, one <tbody> per dataset, same cells as RESULTS.md.
    for dataset, trs in site_rows.items():
        print(f"<!-- {dataset}: {len(trs)} rows -->")
        print("\n".join(trs))
    print(f"<!-- {len(rows)} cells from {len(reports)} runs, hard-gate total {gates_total}, "
          f"{superseded_fail} superseded failing cell(s) kept in Notes -->", file=sys.stderr)
    sys.exit(0)
open(os.path.join(root, "RESULTS.md"), "w").write("\n".join(out) + "\n")
print(f"wrote RESULTS.md: {len(rows)} cells, gates={gates_total}")
